/* ── SEARCH ── */
const searchInput = document.getElementById('search');
const searchResults = document.getElementById('searchResults');
const searchGrid = document.getElementById('searchGrid');
const searchLabel = document.getElementById('searchLabel');
const noResultsMsg = document.getElementById('noResultsMsg');

searchInput.addEventListener('input', function() {
    const val = this.value.toLowerCase().trim();

    if (!val) {
        searchResults.classList.remove('visible');
        noResultsMsg.style.display = 'none';
        return;
    }

    const matched = Object.keys(destData).filter(key =>
        destData[key].name.toLowerCase().includes(val)
    );

    if (matched.length === 0) {
        searchResults.classList.remove('visible');
        noResultsMsg.style.display = 'block';
        return;
    }

    noResultsMsg.style.display = 'none';

    const key = matched[0];
    const dest = destData[key];

    searchLabel.textContent = dest.name;

    searchGrid.innerHTML = dest.photos.map((p, i) => `
    <div class="search-card" style="animation-delay:${i * 0.07}s" onclick="selectDest('${key}')">
      <div class="search-card-img">
        <img
          src="${p.url}"
          alt="${p.cap}"
          loading="lazy"
          onerror="this.onerror=null; this.src='${FALLBACK}'"
        />
      </div>
      <div class="search-card-body">
        <h4>${dest.name}</h4>
        <p>${p.cap}</p>
      </div>
    </div>
  `).join('');

    searchResults.classList.add('visible');
});

function selectDest(key) {
    document.getElementById('destination').value = key;
    document.getElementById('planner').scrollIntoView({ behavior: 'smooth' });
    showToast(destData[key].name + ' selected in planner!');
}

document.getElementById('planBtn').addEventListener('click', planTrip);

function planTrip() {
    const dest = document.getElementById('destination').value;
    const budget = parseInt(document.getElementById('budget').value);
    const result = document.getElementById('result');
    const min = prices[dest];
    const bd = breakdown[dest];
    const name = destData[dest].name;

    if (!budget || isNaN(budget)) {
        showToast('⚠️ Please enter your budget first!');
        return;
    }

    const canGo = budget >= min;
    const diff = Math.abs(budget - min);

    if (canGo) {
        result.innerHTML = `
      <div class="result-card success">
        <div class="result-icon">✅</div>
        <h3>Yes! ${name} is doable.</h3>
        <p class="verdict-line">
          Your ₹${budget.toLocaleString('en-IN')} covers this trip.
          You will have ₹${diff.toLocaleString('en-IN')} left to spare.
        </p>
        <div class="result-breakdown">
          <div class="breakdown-item"><span>✈️ Transport</span><span>₹${bd.transport.toLocaleString('en-IN')}</span></div>
          <div class="breakdown-item"><span>🏨 Hotel (3 nights)</span><span>₹${bd.hotel.toLocaleString('en-IN')}</span></div>
          <div class="breakdown-item"><span>🍛 Food &amp; dining</span><span>₹${bd.food.toLocaleString('en-IN')}</span></div>
          <div class="breakdown-item"><span>🎟️ Activities</span><span>₹${bd.activities.toLocaleString('en-IN')}</span></div>
        </div>
      </div>`;
    } else {
        result.innerHTML = `
      <div class="result-card fail">
        <div class="result-icon">❌</div>
        <h3>Budget a little short.</h3>
        <p class="verdict-line">
          You need ₹${diff.toLocaleString('en-IN')} more for ${name}.
          Try saving up or pick a more affordable destination.
        </p>
        <div class="result-breakdown">
          <div class="breakdown-item"><span>Your budget</span><span>₹${budget.toLocaleString('en-IN')}</span></div>
          <div class="breakdown-item"><span>Minimum needed</span><span>₹${min.toLocaleString('en-IN')}</span></div>
          <div class="breakdown-item"><span>Shortfall</span><span>₹${diff.toLocaleString('en-IN')}</span></div>
        </div>
      </div>`;
    }
}

function showToast(msg) {
    const t = document.getElementById('toast');
    t.textContent = msg;
    t.classList.add('show');
    setTimeout(() => t.classList.remove('show'), 2500);
}

const observer = new IntersectionObserver(entries => {
    entries.forEach(e => {
        if (e.isIntersecting) {
            e.target.style.opacity = '1';
            e.target.style.transform = 'translateY(0)';
        }
    });
}, { threshold: 0.1 });

document.querySelectorAll('.card').forEach((card, i) => {
    card.style.opacity = '0';
    card.style.transform = 'translateY(30px)';
    card.style.transition =
        `opacity 0.5s ${i * 0.06}s,
     transform 0.5s ${i * 0.06}s cubic-bezier(0.16,1,0.3,1),
     box-shadow 0.4s`;
    observer.observe(card);
});
